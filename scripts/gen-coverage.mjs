// Writes COVERAGE.md from the built registry. Run after `pnpm build`.
import { readFileSync, writeFileSync } from "node:fs";
import { countryName, listSupportedCountries } from "../dist/index.js";
import { TERRITORY_PARENTS } from "../dist/core/countries.js";

const countries = listSupportedCountries();
const own = new Set(countries.map((c) => c.alpha2));
const docs = countries.flatMap((c) => c.documents);
const unsupported = Object.entries(JSON.parse(readFileSync(new URL("./unsupported.json", import.meta.url), "utf8"))).filter(
  ([k]) => k !== "_note",
);
const viaParent = Object.entries(TERRITORY_PARENTS).filter(([t]) => !own.has(t));
const name = (c) => `${countryName(c)} (${c})`;

const lines = [
  "# Coverage",
  "",
  "Generated by `pnpm coverage:docs`. Don't edit by hand; reasons for unsupported places live in `scripts/unsupported.json`.",
  "",
  `**${countries.length} countries/territories with their own rules, ${docs.length} document types** ` +
    `(${docs.filter((d) => d.checksum).length} with a verified check digit), plus ${viaParent.length} territories ` +
    `covered through a parent country. ${unsupported.length} researched and not supported.`,
  "",
  "✓ = check digit verified · confidence: H high, M moderate, L low",
  "",
  "## Supported",
  "",
  "| Country | Documents |",
  "|---|---|",
  ...countries.map(
    (c) =>
      `| ${c.name} (${c.alpha2}) | ${c.documents
        .map((d) => `\`${d.code}\`${d.checksum ? " ✓" : ""} ${d.confidence[0].toUpperCase()}`)
        .join(" · ")} |`,
  ),
  "",
  "## Covered through a parent country",
  "",
  "Passing one of these as `country` tries the parent's documents.",
  "",
  "| Territory | Uses |",
  "|---|---|",
  ...viaParent.map(([t, ps]) => `| ${name(t)} | ${ps.map(name).join(", ")} |`),
  "",
  "## Researched, not supported",
  "",
  "No documented format could be found. Specimens or official specs would let these be added.",
  "",
  "| Country | Why |",
  "|---|---|",
  ...unsupported.sort(([a], [b]) => a.localeCompare(b)).map(([c, why]) => `| ${name(c)} | ${why} |`),
  "",
];
writeFileSync(new URL("../COVERAGE.md", import.meta.url), lines.join("\n"));
console.log(`COVERAGE.md: ${countries.length} own, ${viaParent.length} via parent, ${unsupported.length} unsupported`);
