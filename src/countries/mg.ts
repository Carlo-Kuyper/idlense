/**
 * Madagascar — CIN number and the tax NIF. Neither has a published check
 * algorithm, so both are shape-only.
 *
 * MG_CIN, the 12-digit number on the Kara-panondro (Carte d'Identité
 * Nationale). It stays the same when the card is renewed. The World Bank ID4D
 * diagnostic (2017, p. 13) gives its layout as XXX YY Z NNNNNN:
 * - XXX    district code
 * - YY     commune code within the district
 * - Z      sex
 * - NNNNNN chronological serial
 * No source says which value of Z means which sex, so we return the raw digit
 * in `extra.sexDigit` and set no `gender`. No district table is published, so
 * `region` is the raw code. The same report warns that numbers are assembled by
 * hand and duplicates and clerical errors exist, so we don't check ranges.
 * A single (reputable) source, so confidence is `low`.
 *
 * MG_NIF, the Numéro d'Identification Fiscale from the Direction Générale des
 * Impôts: 10 digits, generated by the online registration system. The World
 * Bank report says a control key sits at each end around an 8-digit random
 * sequence, but the algorithm isn't known, so we don't verify it. The length is
 * matched by the example in org-id.guide's registry entry. Issued to persons
 * and companies; confidence `moderate`.
 */
import { digitsOnly, group } from "../core/normalize.js";
import type { DocumentSpec } from "../core/types.js";

const WB_ID4D = "https://documents1.worldbank.org/curated/en/809191510763351833/ID4D-Country-Diagnostic-Madagascar.pdf";

export const documents: DocumentSpec[] = [
  {
    code: "MG_CIN",
    country: "MG",
    name: "Malagasy National Identity Card Number",
    localName: "Kara-panondro (Carte d'Identité Nationale)",
    aliases: ["CIN", "CNI", "karapanondro"],
    purpose: "identity",
    holder: "person",
    checksum: false,
    confidence: "low",
    lengths: [12],
    pattern: /^\d{12}$/,
    example: "101011123456",
    sources: [WB_ID4D],
    normalize: digitsOnly,
    format: (c) => group(c, [3, 3, 3, 3], " "),
    parse(id) {
      return {
        ok: true,
        data: {
          region: id.slice(0, 3),
          serial: id.slice(6),
          extra: { communeCode: id.slice(3, 5), sexDigit: id[5]! },
        },
      };
    },
  },
  {
    code: "MG_NIF",
    country: "MG",
    name: "Malagasy Tax Identification Number",
    localName: "Numéro d'Identification Fiscale",
    aliases: ["NIF"],
    purpose: "tax",
    holder: "both",
    checksum: false,
    confidence: "moderate",
    lengths: [10],
    pattern: /^\d{10}$/,
    example: "4001257310",
    sources: [WB_ID4D, "https://org-id.guide/list/MG-NIF"],
    normalize: digitsOnly,
    parse(id) {
      return { ok: true, data: { serial: id.slice(1, 9), extra: {} } };
    },
  },
];
